import { readFileSync } from "node:fs";

const [beforePath, afterPath] = process.argv.slice(2);

if (!beforePath || !afterPath || process.argv.includes("--help")) {
    console.log(`
Compare two reports generated by scripts/audit-offer-data-quality.mjs.

Usage:
  node scripts/compare-offer-audit-reports.mjs reports/audit-before.json reports/audit-after.json

Recommended:
  node scripts/audit-offer-data-quality.mjs --json --write-report reports/audit-before.json
  # apply one small thumbnail/task batch
  node scripts/audit-offer-data-quality.mjs --json --write-report reports/audit-after.json
  node scripts/compare-offer-audit-reports.mjs reports/audit-before.json reports/audit-after.json
`);
    process.exit(beforePath && afterPath ? 0 : 1);
}

const before = readJson(beforePath);
const after = readJson(afterPath);

const rows = [
    compareMetric("active_taskless_offers", sumValues(before.issues?.missingTasks), sumValues(after.issues?.missingTasks)),
    compareMetric("games_missing_thumbnails", before.totals?.gamesMissingThumbnail, after.totals?.gamesMissingThumbnail),
    compareMetric("thumbnail_candidates", before.totals?.gamesWithOfferThumbnailCandidate, after.totals?.gamesWithOfferThumbnailCandidate),
    compareMetric("active_missing_images", sumValues(before.issues?.missingImages), sumValues(after.issues?.missingImages)),
    compareMetric("public_low_payout_rows", sumValues(before.issues?.ultraLowPayouts), sumValues(after.issues?.ultraLowPayouts)),
    compareMetric("total_payout_below_payout", before.issues?.totalPayoutBelowPayout, after.issues?.totalPayoutBelowPayout),
];

console.log(JSON.stringify({
    before: beforePath,
    after: afterPath,
    compared_at: new Date().toISOString(),
    metrics: rows,
}, null, 2));

function readJson(path) {
    return JSON.parse(readFileSync(path, "utf8"));
}

function sumValues(value) {
    if (!value || typeof value !== "object") return Number(value ?? 0) || 0;
    return Object.values(value).reduce((sum, next) => sum + (Number(next) || 0), 0);
}

function compareMetric(name, beforeValue, afterValue) {
    const beforeNumber = Number(beforeValue ?? 0);
    const afterNumber = Number(afterValue ?? 0);
    return {
        name,
        before: beforeNumber,
        after: afterNumber,
        delta: afterNumber - beforeNumber,
    };
}
