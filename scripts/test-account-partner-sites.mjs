import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
const read = (file) => readFileSync(path.join(process.cwd(), file), "utf8");
const migration = read("supabase/migrations/20260721230048_add_user_gpt_partner_accounts.sql");
const redirect = read("src/app/go/platform/[platformId]/route.ts");
const account = read("src/app/account/page.tsx");
const partners = read("src/components/account/AccountPartnerSites.tsx");
assert.match(migration, /references auth\.users\(id\) on delete cascade/, "partner records must cascade with the Auth user");
assert.match(migration, /references public\.platforms\(id\) on delete cascade/, "partner records must reference a real platform");
assert.match(migration, /unique \(user_id, platform_id\)/, "a user can have one connection per platform");
assert.match(migration, /enable row level security/, "partner records must enable RLS");
assert.match(migration, /auth\.uid\(\)\) = user_id/, "partner records must be self-scoped");
assert.match(redirect, /user_gpt_partner_accounts/, "platform redirects must persist a signed-in partner signup click");
assert.match(redirect, /onConflict: "user_id,platform_id"/, "repeated partner clicks must update one record");
assert.match(account, /AccountPartnerSites/, "the private account page must render partner connections");
assert.match(partners, /Open a partner from here/, "the profile must explain the signup-link state honestly");
assert.match(partners, /<a href=/, "partner links must be regular anchors and never prefetched redirects");
console.log("Account partner signup guard passed");
