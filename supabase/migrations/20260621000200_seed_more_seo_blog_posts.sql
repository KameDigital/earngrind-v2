## Why pending exists

Advertisers do not always pay immediately after a user reaches a milestone. They may check whether the install was new, whether the device matched the click, whether the task was completed inside the deadline, whether purchases were refunded, or whether the account triggered fraud filters.

Offerwalls and GPT sites may add their own review windows before releasing the reward. That is why one milestone can show as complete but still not be withdrawable.

## Common pending windows

There is no universal timer. Light tasks may credit quickly. Larger mobile game offers often include delayed confirmation. Purchase tasks, subscription trials, high-value levels, and multi-step campaigns usually receive more review.

Before starting, read the offer terms for phrases like pending, hold, manual review, approval time, chargeback period, or advertiser validation. Screenshot those terms.

If the task gives no timeline, assume support will ask you to wait at least through the normal provider window before reviewing proof.

## What to do while pending

Do not panic-click the same offer on another wall. Duplicate attempts can create more risk.

While pending:

- Keep the app installed.
- Keep your game account accessible.
- Save proof of the completed milestone.
